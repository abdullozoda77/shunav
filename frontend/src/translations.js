const DICTIONARIES = { tg: TG, ru: RU, en: EN };

export const LANGUAGES = [
  { code: "tg", short: "TG", name: "Тоҷикӣ" },
  { code: "ru", short: "RU", name: "Русский" },
  { code: "en", short: "EN", name: "English" },
];

// The language now on the screen. Set by LanguageProvider (i18n.jsx); format.js reads it for "5 мин" / "5 min".
let current = "tg";

export function setCurrentLanguage(language) {
  current = language;
}

export function getCurrentLanguage() {
  return current;
}

function pluralForm(forms, n, language) {
  if (language === "ru") {
    const last = n % 10;
    const lastTwo = n % 100;
    if (last === 1 && lastTwo !== 11) return forms[0];
    if (last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14)) return forms[1];
    return forms[2];
  }
  return n === 1 ? forms[0] : forms[1];
}

export function translate(text, values, language = current) {
  if (!text) return text;
  const dictionary = DICTIONARIES[language];
  let result = dictionary?.[text];
  // a longer text from the database: each paragraph on its own (they share the paragraph about Ganjoor)
  if (result === undefined && text.includes("\n\n")) {
    result = text
      .split("\n\n")
      .map((paragraph) => dictionary?.[paragraph] ?? paragraph)
      .join("\n\n");
  }
  result ??= text;
  if (Array.isArray(result)) result = pluralForm(result, values?.n ?? 0, language);
  if (values) result = result.replace(/\{(\w+)\}/g, (match, key) => (key in values ? values[key] : match));
  return result;
}
